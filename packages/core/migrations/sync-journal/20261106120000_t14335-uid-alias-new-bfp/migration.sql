-- T14335 (T14334a; T12341 §6.4 step 1) — a uid alias carries the re-key's
-- new birth fingerprint.
--
-- _sync_uid_alias.new_bfp: the K's `bfp`, the row's birth fingerprint after
--   the re-key. A re-key that moves the fingerprint too (an old-recipe row
--   rewritten onto a shared identity) used to leave a held loser's ops on
--   the OLD fingerprint once they followed the alias, so they arrived as
--   (new uid, old fingerprint), collided with the winner, and the loser's
--   origin re-keyed it to a random uid: the row forked. Following the alias
--   now rewrites the fingerprint as well. NULL for aliases recorded before
--   this column, and for re-keys that keep the fingerprint: the follow then
--   keeps the op's own.
--
-- Local-only, both stores. The wire is unchanged: a K already carries `bfp`.
--
-- Do not edit this file once applied: its hash is recorded per store.
ALTER TABLE _sync_uid_alias ADD COLUMN new_bfp TEXT;
