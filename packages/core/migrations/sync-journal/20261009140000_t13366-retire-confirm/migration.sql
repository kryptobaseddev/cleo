-- T13366 (journal spec §1.5 "Retirement") — a retire counts only once the
-- server confirmed it.
--
-- _sync_retired.confirmed_at: when the server's own record of this
-- retirement (the E31 answer to the emitter, or `retiredAt` and `successor`
-- on the home replica listing) named the same successor; NULL until then.
-- An unconfirmed retire changes nothing: the retired replica's later
-- transactions apply with their conflicts recorded, and the fold horizon and
-- the remint authority still count the replica. The server accepts a
-- retirement only from the replica's pinned device or, on a project stream,
-- an owner's device (`not-pinned-or-owner`; on a home stream any device of
-- the account), so a signed `retire` transaction alone cannot retire another
-- device's project replica.
--
-- Local-only.
--
-- Do not edit this file once applied: its hash is recorded per store.
ALTER TABLE _sync_retired ADD COLUMN confirmed_at TEXT;
