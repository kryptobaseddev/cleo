/**
 * Canonical agent definitions rendered into provider agent files (T14378).
 *
 * The canonical lead and worker live as `.cant` files in `@cleocode/agents`
 * (`definitions/`). They use a flat subset of the CANT agent grammar: one
 * `agent <name>:` block whose properties are single-line `key: value` pairs
 * (quoted strings, `true`/`false`, or `[a, b]` lists). This reader needs no
 * native addon, so delivery works on every OS and in any project.
 *
 * Each provider that loads project agent files declares where and in which
 * format in the registry (`agentDefinitions`); this module renders one
 * definition into that format.
 *
 * @task T14378
 * @epic T14351
 */

import type { AgentDefinitionFormat } from '../registry/types.js';

/**
 * A canonical agent definition read from a `.cant` file.
 *
 * @public
 */
export interface AgentDefinition {
  /** Agent name (kebab-case); also the rendered file's base name. */
  name: string;
  /** Declared role: `lead` agents talk to the owner and dispatch; `worker` agents do the work. */
  role: 'lead' | 'worker';
  /** When the harness should use this agent. */
  description: string;
  /** System prompt. */
  prompt: string;
  /** Tool allowlist; absent means every tool the harness offers. */
  tools?: string[];
  /** Tools the agent must never get, removed even when inherited. */
  deniedTools?: string[];
  /** Whether the agent always runs as a background task. */
  background?: boolean;
  /**
   * MCP stdio servers started for this agent only, keyed by server name.
   * Set by delivery (the lead's command runner, T14374), not by `.cant` files.
   */
  mcpServers?: Record<string, AgentMcpServer>;
}

/**
 * An MCP stdio server an agent definition starts for itself.
 *
 * @public
 */
export interface AgentMcpServer {
  /** Executable to start. */
  command: string;
  /** Arguments, passed without a shell. */
  args: string[];
}

/**
 * A rendered provider agent file.
 *
 * @public
 */
export interface RenderedAgentDefinition {
  /** File name inside the provider's agent directory. */
  fileName: string;
  /** Full file content. */
  content: string;
}

/**
 * Line CAAMP writes into every agent file it renders. A file without it is
 * owned by the user and is never overwritten.
 *
 * @public
 */
export const AGENT_DEFINITION_MARKER =
  '# Generated by CLEO (cleo init / cleo upgrade). Edits are overwritten; copy the file under another name to customise.';

type CantValue = string | boolean | string[];

/** Decode a double-quoted CANT string (JSON string escapes). */
function parseQuoted(raw: string, key: string): string {
  const value: unknown = JSON.parse(raw);
  if (typeof value !== 'string') throw new Error(`agent definition: bad string for "${key}"`);
  return value;
}

/** Parse one single-line CANT property value. */
function parseValue(raw: string, key: string): CantValue {
  const v = raw.trim();
  if (v === 'true') return true;
  if (v === 'false') return false;
  if (v.startsWith('"')) return parseQuoted(v, key);
  if (v.startsWith('[')) {
    if (!v.endsWith(']')) throw new Error(`agent definition: unterminated list for "${key}"`);
    return v
      .slice(1, -1)
      .split(',')
      .map((item) => item.trim())
      .filter((item) => item.length > 0)
      .map((item) => (item.startsWith('"') ? parseQuoted(item, key) : item));
  }
  return v;
}

function requireString(props: Map<string, CantValue>, key: string): string {
  const value = props.get(key);
  if (typeof value !== 'string' || value.length === 0) {
    throw new Error(`agent definition: "${key}" must be a non-empty string`);
  }
  return value;
}

function optionalList(props: Map<string, CantValue>, key: string): string[] | undefined {
  const value = props.get(key);
  if (value === undefined) return undefined;
  if (!Array.isArray(value)) throw new Error(`agent definition: "${key}" must be a list`);
  return value;
}

const KNOWN_KEYS = new Set([
  'role',
  'description',
  'prompt',
  'tools',
  'denied-tools',
  'background',
]);

/**
 * Read a canonical agent definition from `.cant` content.
 *
 * @param cant - Raw `.cant` file content (frontmatter `kind: agent`).
 * @returns The definition.
 * @throws When the file is not a flat agent definition, a key is unknown, or a
 *   required key (`role`, `description`, `prompt`) is missing.
 *
 * @example
 * ```typescript
 * const def = parseAgentDefinition(readFileSync('cleo-lead.cant', 'utf-8'));
 * def.role; // 'lead'
 * ```
 *
 * @public
 */
export function parseAgentDefinition(cant: string): AgentDefinition {
  const fm = cant.match(/^---\s*\n([\s\S]*?)\n---\s*\n([\s\S]*)$/);
  if (!fm || !/^kind:\s*agent\s*$/m.test(fm[1] ?? '')) {
    throw new Error('agent definition: frontmatter with "kind: agent" is required');
  }
  const lines = (fm[2] ?? '').split('\n');
  const start = lines.findIndex((l) => /^agent\s+[\w-]+:\s*$/.test(l));
  if (start < 0) throw new Error('agent definition: no "agent <name>:" block');
  const name = (lines[start] ?? '').replace(/^agent\s+/, '').replace(/:\s*$/, '');

  const props = new Map<string, CantValue>();
  for (const line of lines.slice(start + 1)) {
    if (line.trim() === '' || line.trim().startsWith('#')) continue;
    if (!line.startsWith('  ')) break;
    const m = line.match(/^ {2}([\w-]+):\s+(.+)$/);
    if (!m) throw new Error(`agent definition: unsupported line "${line.trim()}"`);
    const key = m[1] ?? '';
    if (!KNOWN_KEYS.has(key)) throw new Error(`agent definition: unknown key "${key}"`);
    props.set(key, parseValue(m[2] ?? '', key));
  }

  const role = requireString(props, 'role');
  if (role !== 'lead' && role !== 'worker') {
    throw new Error(`agent definition: role must be "lead" or "worker", got "${role}"`);
  }
  const background = props.get('background');
  if (background !== undefined && typeof background !== 'boolean') {
    throw new Error('agent definition: "background" must be true or false');
  }
  const tools = optionalList(props, 'tools');
  const deniedTools = optionalList(props, 'denied-tools');
  return {
    name,
    role,
    description: requireString(props, 'description'),
    prompt: requireString(props, 'prompt'),
    ...(tools ? { tools } : {}),
    ...(deniedTools ? { deniedTools } : {}),
    ...(background !== undefined ? { background } : {}),
  };
}

/** OpenCode permission key gating each denied Claude-style tool name. */
const OPENCODE_PERMISSION: Readonly<Record<string, string>> = {
  Bash: 'bash',
  Edit: 'edit',
  Write: 'edit',
  MultiEdit: 'edit',
  NotebookEdit: 'edit',
  WebFetch: 'webfetch',
  WebSearch: 'websearch',
};

function renderClaude(def: AgentDefinition): string {
  const fm = [
    '---',
    AGENT_DEFINITION_MARKER,
    `name: ${def.name}`,
    `description: ${JSON.stringify(def.description)}`,
  ];
  if (def.tools) fm.push(`tools: ${JSON.stringify(def.tools.join(', '))}`);
  if (def.deniedTools) fm.push(`disallowedTools: ${JSON.stringify(def.deniedTools.join(', '))}`);
  if (def.background !== undefined) fm.push(`background: ${def.background}`);
  const servers = Object.entries(def.mcpServers ?? {});
  if (servers.length > 0) {
    // Inline per-agent servers: a list of single-key maps (Claude Code sub-agent docs).
    fm.push('mcpServers:');
    for (const [name, server] of servers) {
      fm.push(`  - ${name}:`, '      type: stdio');
      fm.push(`      command: ${JSON.stringify(server.command)}`);
      fm.push(`      args: ${JSON.stringify(server.args)}`);
    }
  }
  fm.push('---');
  return `${fm.join('\n')}\n\n${def.prompt}\n`;
}

/**
 * Why a format cannot express a definition, or `undefined` when it can.
 *
 * The OpenCode format writes only `permission` denies: it has no tool
 * allow-list and no per-agent MCP servers, so a definition with `tools` or
 * `mcpServers` would get every other tool there (global MCP tools, `task`).
 * Such a definition is not delivered to that provider (T14374).
 *
 * @param def - The canonical definition, as delivered.
 * @param format - The provider's format (registry `agentDefinitions.format`).
 * @returns The reason, or `undefined` when {@link renderAgentDefinition} can render it.
 *
 * @example
 * ```typescript
 * agentDefinitionUnsupportedReason(lead, 'opencode'); // 'OpenCode agent files cannot ...'
 * ```
 *
 * @public
 */
export function agentDefinitionUnsupportedReason(
  def: AgentDefinition,
  format: AgentDefinitionFormat,
): string | undefined {
  if (format === 'claude-code') return undefined;
  if (def.tools || Object.keys(def.mcpServers ?? {}).length > 0) {
    return 'OpenCode agent files cannot restrict tools to an allow-list or declare per-agent MCP servers';
  }
  return undefined;
}

function renderOpenCode(def: AgentDefinition): string {
  const unsupported = agentDefinitionUnsupportedReason(def, 'opencode');
  if (unsupported) throw new Error(`agent definition "${def.name}": ${unsupported}`);
  const fm = [
    '---',
    AGENT_DEFINITION_MARKER,
    `description: ${JSON.stringify(def.description)}`,
    // A lead converses with the owner (primary); a worker is dispatched (subagent).
    `mode: ${def.role === 'lead' ? 'primary' : 'subagent'}`,
  ];
  const keys = new Set<string>();
  for (const tool of def.deniedTools ?? []) {
    const key = OPENCODE_PERMISSION[tool];
    if (!key) throw new Error(`agent definition: no OpenCode permission gates "${tool}"`);
    keys.add(key);
  }
  if (keys.size > 0) {
    fm.push('permission:');
    for (const key of [...keys].sort()) fm.push(`  ${key}: deny`);
  }
  fm.push('---');
  return `${fm.join('\n')}\n\n${def.prompt}\n`;
}

/**
 * Render a canonical definition into a provider's agent-file format.
 *
 * @param def - The canonical definition.
 * @param format - The provider's format (registry `agentDefinitions.format`).
 * @returns File name and content; the content carries {@link AGENT_DEFINITION_MARKER}.
 * @throws When a denied tool has no equivalent in the target format, so a
 *   lead is never written with a tool it must not have.
 *
 * @example
 * ```typescript
 * renderAgentDefinition(lead, 'claude-code').fileName; // 'cleo-lead.md'
 * ```
 *
 * @public
 */
export function renderAgentDefinition(
  def: AgentDefinition,
  format: AgentDefinitionFormat,
): RenderedAgentDefinition {
  const content = format === 'claude-code' ? renderClaude(def) : renderOpenCode(def);
  return { fileName: `${def.name}.md`, content };
}

/**
 * Whether an agent file was written by CAAMP (and may be refreshed).
 *
 * @param content - The file's current content.
 *
 * @public
 */
export function isGeneratedAgentDefinition(content: string): boolean {
  return content.includes(AGENT_DEFINITION_MARKER);
}
