#!/usr/bin/env node
/**
 * Build-time generator: scans `packages/cleo/src/cli/commands/*.ts` and emits
 * `packages/cleo/src/cli/generated/command-manifest.ts` — a static index of
 * `{ exportName, importPath, meta: { name, description } }` for every exported
 * `xxxCommand` constant.
 *
 * Why
 * ----
 * The CLI entry point uses this manifest to register lazy command wrappers:
 * `meta` is read eagerly (so `--help` works without loading every command),
 * and the actual command module is `import()`-ed only when the user runs it.
 *
 * Each command file remains the single source of truth for its own metadata —
 * this script just bridges that to a static index the bundler can analyse.
 */

import { execFileSync } from 'node:child_process';
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const PKG_ROOT = resolve(__dirname, '..');
/** Monorepo root — `packages/cleo` is two levels down. */
const REPO_ROOT = resolve(PKG_ROOT, '..', '..');
/**
 * `--check` verifies without writing.
 *
 * `pretypecheck` and `prebuild` use it, because a build step must NOT mutate a
 * tracked file: it dirties every agent's working tree and changes the evidence
 * cache fingerprint as a side effect of running a tool (gh#1306).
 */
const CHECK_ONLY = process.argv.slice(2).includes('--check');
const COMMANDS_DIR = join(PKG_ROOT, 'src', 'cli', 'commands');
const OUTPUT_DIR = join(PKG_ROOT, 'src', 'cli', 'generated');
const OUTPUT_FILE = join(OUTPUT_DIR, 'command-manifest.ts');

/**
 * Match `export const fooCommand = defineCommand({` (with optional `as CommandDef`
 * type assertions) plus the immediately-following `meta: { name: '...', description: '...' }`
 * block. Multi-line descriptions are captured inside the same string literal.
 */
const COMMAND_BLOCK_RE =
  /export\s+const\s+(\w+Command)\s*(?::\s*\w+)?\s*=\s*defineCommand\s*\(\s*\{[\s\S]*?meta\s*:\s*\{([\s\S]*?)\}/g;

const NAME_RE = /name\s*:\s*['"`]([^'"`]+)['"`]/;
const DESC_RE = /description\s*:\s*['"`]((?:[^'"`\\]|\\.)*)['"`]/;

function extractFromFile(file) {
  const text = readFileSync(file, 'utf8');
  const results = [];
  let match;
  while ((match = COMMAND_BLOCK_RE.exec(text)) !== null) {
    const exportName = match[1];
    const metaBlock = match[2];
    const nameMatch = metaBlock.match(NAME_RE);
    const descMatch = metaBlock.match(DESC_RE);
    if (!nameMatch) continue; // skip if no name field
    results.push({
      exportName,
      name: nameMatch[1],
      description: descMatch ? descMatch[1] : '',
    });
  }
  return results;
}

function main() {
  const files = readdirSync(COMMANDS_DIR)
    .filter((f) => f.endsWith('.ts') && !f.endsWith('.test.ts'))
    .sort();

  const entries = [];
  for (const f of files) {
    const path = join(COMMANDS_DIR, f);
    const fileEntries = extractFromFile(path);
    for (const e of fileEntries) {
      entries.push({
        ...e,
        // Import path used at runtime — relative to cli/generated/
        importPath: `../commands/${f.replace(/\.ts$/, '.js')}`,
        // Whether this export is a SubCommand-only binding (mounted under a
        // parent command). SubCommands MAY share a `meta.name` with a
        // top-level command — the parent command's `subCommands` table
        // disambiguates at run time (e.g. `cleo verify` vs `cleo backup verify`).
        isSubCommand: /SubCommand$/.test(e.exportName),
      });
    }
  }

  if (entries.length === 0) {
    console.error('generate-command-manifest: no commands found in', COMMANDS_DIR);
    process.exit(1);
  }

  // Detect duplicate command names so we surface conflicts at build time.
  // SubCommand exports are skipped when a non-SubCommand owns the name — the
  // SubCommand is mounted under its parent in source and never collides at
  // the top level. Two TOP-level commands sharing a name is still an error.
  const topLevelByName = new Map();
  for (const e of entries) {
    if (e.isSubCommand) continue;
    const prev = topLevelByName.get(e.name);
    if (prev && prev.exportName !== e.exportName) {
      console.error(
        `generate-command-manifest: duplicate command name "${e.name}" — ` +
          `${prev.exportName} (${prev.importPath}) and ${e.exportName} (${e.importPath})`,
      );
      process.exit(1);
    }
    topLevelByName.set(e.name, e);
  }
  // Prune SubCommand entries whose name is already owned by a top-level
  // command — keeping them in the manifest would silently override the
  // top-level binding via `subCommands[entry.name] = wrapper` in
  // `packages/cleo/src/cli/index.ts`.
  for (let i = entries.length - 1; i >= 0; i--) {
    const e = entries[i];
    if (e.isSubCommand && topLevelByName.has(e.name)) {
      entries.splice(i, 1);
    }
  }

  const banner = `/**
 * AUTO-GENERATED by packages/cleo/scripts/generate-command-manifest.mjs.
 * DO NOT EDIT MANUALLY — regenerate via \`pnpm --filter @cleocode/cleo run gen:manifest\`.
 *
 * This file is the eagerly-loaded index of CLI commands. Each entry carries the
 * static \`meta\` plus a dynamic \`load()\` that imports the command on demand.
 *
 * The point: \`cleo --help\` and \`cleo --version\` no longer transitively load
 * 111 command modules + their CORE/SQLite/drizzle dependency trees. Only the
 * matched command's module is loaded at run time.
 */

import type { CommandDef } from 'citty';

/**
 * One entry per exported \`xxxCommand\` discovered in src/cli/commands/.
 * Identified by both \`exportName\` (some files export multiple commands)
 * and \`name\` (the user-facing CLI subcommand).
 */
export interface CommandManifestEntry {
  /** The exported binding inside the command module (e.g. \`findCommand\`). */
  readonly exportName: string;
  /** The user-facing CLI name (e.g. \`find\`). Matches \`meta.name\` in source. */
  readonly name: string;
  /** Short description shown in \`cleo --help\`. Matches \`meta.description\` in source. */
  readonly description: string;
  /** Dynamic import — resolves to the full \`CommandDef\` only when invoked. */
  readonly load: () => Promise<CommandDef>;
}
`;

  const lines = [banner, '', 'export const COMMAND_MANIFEST: readonly CommandManifestEntry[] = [', ];
  for (const e of entries) {
    const desc = e.description.replace(/'/g, "\\'");
    lines.push(
      `  {`,
      `    exportName: '${e.exportName}',`,
      `    name: '${e.name}',`,
      `    description: '${desc}',`,
      `    load: async () => (await import('${e.importPath}')).${e.exportName} as CommandDef,`,
      `  },`,
    );
  }
  lines.push('] as const;', '');

  const formatted = formatSource(lines.join('\n'));
  const rel = OUTPUT_FILE.replace(`${PKG_ROOT}/`, '');

  if (CHECK_ONLY) {
    let committed;
    try {
      committed = readFileSync(OUTPUT_FILE, 'utf8');
    } catch {
      console.error(
        `generate-command-manifest: ${rel} is MISSING.\n` +
          '  Create it with: pnpm --filter @cleocode/cleo run gen:manifest',
      );
      process.exit(1);
    }
    if (committed === formatted) {
      console.info(`generate-command-manifest: ${rel} is current (${entries.length} entries).`);
      return;
    }
    console.error(
      `\ngenerate-command-manifest: ${rel} is STALE.\n\n` +
        '  The committed manifest does not match what its generator produces.\n' +
        '  This check does NOT rewrite it — a typecheck or build must not mutate\n' +
        '  tracked files (gh#1306): doing so dirties every agent\'s tree and changes\n' +
        '  the evidence-cache fingerprint as a side effect of running a tool.\n\n' +
        '  FIX:  pnpm --filter @cleocode/cleo run gen:manifest\n' +
        `        git add ${rel} && git commit\n`,
    );
    process.exit(1);
  }

  mkdirSync(OUTPUT_DIR, { recursive: true });
  writeFileSync(OUTPUT_FILE, formatted, 'utf8');
  console.info(`generate-command-manifest: wrote ${entries.length} entries to ${rel}`);
}

/**
 * Return `source` as biome would format it.
 *
 * The generator used to emit unformatted output which biome then reformatted on
 * commit, so every regeneration produced ~183 lines of pure formatting diff. That
 * noise is not cosmetic: it CAMOUFLAGES real drift. Two commands
 * (`doctor memory-guard`, `doctor superseded-store`) were missing from the
 * committed manifest for weeks inside that noise. Formatting here means a diff
 * means content, and nothing else.
 *
 * Falls back to the unformatted source if biome is unavailable, so the generator
 * still works in an environment without dev dependencies.
 */
function formatSource(source) {
  // The scratch file MUST live in the output directory, not in os.tmpdir().
  // Biome resolves configuration and per-path overrides BY PATH, so formatting
  // the same bytes at /tmp and at packages/cleo/src/cli/generated/ produces
  // different output — measured: a temp-path format then reformatted at the
  // real path, which would make `--check` flip-flop forever.
  mkdirSync(OUTPUT_DIR, { recursive: true });
  const scratch = join(OUTPUT_DIR, '.command-manifest.fmt.ts');
  try {
    writeFileSync(scratch, source, 'utf8');
    execFileSync(join(REPO_ROOT, 'node_modules/.bin/biome'), ['format', '--write', scratch], {
      cwd: REPO_ROOT,
      stdio: 'ignore',
    });
    return readFileSync(scratch, 'utf8');
  } catch {
    return source;
  } finally {
    rmSync(scratch, { force: true });
  }
}


main();
